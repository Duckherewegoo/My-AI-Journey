var sameVendorPrefixes = require('../../vendor-prefixes').same;

function understandable(validator, value, value, _position, isPaired) {
  if (!sameVendorPrefixes(value, value)) {
    return false;
  }

  if (isPaired && validator.isVariable(value) !== validator.isVariable(value)) {
    return false;
  }

  return true;
}

module.exports = understandable;
