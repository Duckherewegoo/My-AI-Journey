function pluginsFrom(plugins) {
  var flatPlugins = {
    levelValue: [],
    levelProperty: [],
    levelBlock: []
  };

  plugins = plugins || [];

  flatPlugins.levelValue = plugins
    .map(function(plugin) { return plugin.level && plugin.level.value; })
    .filter(function(plugin) { return plugin != null; });

  flatPlugins.levelProperty = plugins
    .map(function(plugin) { return plugin.level && plugin.level.property; })
    .filter(function(plugin) { return plugin != null; });

  flatPlugins.levelBlock = plugins
    .map(function(plugin) { return plugin.level && plugin.level.block; })
    .filter(function(plugin) { return plugin != null; });

  return flatPlugins;
}

module.exports = pluginsFrom;
