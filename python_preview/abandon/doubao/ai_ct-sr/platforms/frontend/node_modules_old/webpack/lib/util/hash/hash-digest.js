const digest = (hash, encoding, isSafe) => {
	if (typeof encoding === "undefined") {
		return isSafe ? hash.digest() : toBuffer(hash.digest());
	}

	if (encoding === "baseurl" && !isBaseURLSupported) {
		const digest = isSafe
			? hash.digest("base")
			: toString(hash.digest("base"), "base");

		return digest.replace(/\+/g, "-").replace(/\//g, "_").replace(/[=]+$/, "");
	} else if (
		typeof ENCODE_TABLE[/ @type {Base} / (encoding.slice())] !== "undefined"
	) {
		const buf = isSafe ? hash.digest() : toBuffer(hash.digest());

		return encode(
			buf,
			/ @type {Base} /
			(encoding.slice())
		);
	}

	return isSafe
		? hash.digest(encoding)
		: toString(hash.digest(encoding), encoding);
};

