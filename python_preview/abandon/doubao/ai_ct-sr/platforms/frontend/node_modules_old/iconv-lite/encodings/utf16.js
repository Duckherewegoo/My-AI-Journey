// == UTF- codec =============================================================
// Decoder chooses automatically from UTF-LE and UTF-BE using BOM and space-based heuristic.
// Defaults to UTF-LE, as it's prevalent and default in Node.
// http://en.wikipedia.org/wiki/UTF- and http://encoding.spec.whatwg.org/utf-le
// Decoder default can be changed: iconv.decode(buf, 'utf', {defaultEncoding: 'utf-be'});

// Encoder uses UTF-LE and prepends BOM (which can be overridden with addBOM: false).

exports.utf = UtfCodec;
function UtfCodec(codecOptions, iconv) {
    this.iconv = iconv;
}

UtfCodec.prototype.encoder = UtfEncoder;
UtfCodec.prototype.decoder = UtfDecoder;


// -- Encoding (pass-through)

function UtfEncoder(options, codec) {
    options = options || {};
    if (options.addBOM === undefined)
        options.addBOM = true;
    this.encoder = codec.iconv.getEncoder('utf-le', options);
}

UtfEncoder.prototype.write = function(str) {
    return this.encoder.write(str);
}

UtfEncoder.prototype.end = function() {
    return this.encoder.end();
}


