'use strict';

module.exports = ({onlyFirst = false} = {}) => {
	const pattern = [
		'[\\uB\\uB][[\\]();?](?:(?:(?:(?:;[-a-zA-Z\\d\\/&.:=?%@~_]+)|[a-zA-Z\\d]+(?:;[-a-zA-Z\\d\\/&.:=?%@~_]))?\\u)',
		'(?:(?:\\d{,}(?:;\\d{,}))?[\\dA-PR-TZcf-ntqry=><~]))'
	].join('|');

	return new RegExp(pattern, onlyFirst ? undefined : 'g');
};
