'use strict'

const test = require('tape')
const fastURI = require('..')

test('parse marks malformed authority and port inputs as errors', (t) => {
  const malformedCases = [
    {
      input: 'http://[::]foo',
      expectedError: 'URI path must start with "/" when authority is present.'
    },
    {
      input: 'http://[::]:abc/path',
      expectedError: 'URI path must start with "/" when authority is present.'
    },
    {
      input: 'http://example.com:abc/path',
      expectedError: 'URI path must start with "/" when authority is present.'
    },
    {
      input: 'http://[::]:',
      expectedError: 'URI port is malformed.'
    }
  ]

  t.plan(malformedCases.length)

  malformedCases.forEach(({ input, expectedError }) => {
    t.equal(fastURI.parse(input).error, expectedError, input)
  })
})

test('normalize does not canonicalize malformed URLs into different valid URLs', (t) => {
  const malformedCases = [
    'http://[::]foo',
    'http://[::]:abc/path',
    'http://example.com:abc/path',
    'http://[::]:'
  ]

  t.plan(malformedCases.length)

  malformedCases.forEach((input) => {
    t.equal(fastURI.normalize(input), input, input)
  })
})

test('equal returns false when either side is malformed', (t) => {
  const malformedPairs = [
    ['http://[::]foo', 'http://[::]/foo'],
    ['http://[::]:abc/path', 'http://[::]/abc/path'],
    ['http://example.com:abc/path', 'http://example.com/abc/path'],
    ['http://[::]:', 'http://[::]:/']
  ]

  t.plan(malformedPairs.length)

  malformedPairs.forEach(([left, right]) => {
    t.equal(fastURI.equal(left, right), false, `${left} != ${right}`)
  })
})

test('normalize preserves encoded authority delimiters in host', (t) => {
  const cases = [
    ['http://trusted.com%evil.com/', 'http://trusted.com%evil.com/'],
    ['http://example.com%A/', 'http://example.com%A/'],
    ['http://example.com%Fevil.com/path', 'http://example.com%Fevil.com/path'],
    ['http://example.com%fragment/path', 'http://example.com%fragment/path'],
    ['http://example.com%Fq=evil/path', 'http://example.com%Fq=evil/path'],
    ['http://user%Apass%evil.com/', 'http://user%Apass%evil.com/'],
    ['http://user@trusted.com%evil.com/', 'http://user@trusted.com%evil.com/'],
    ['https://trusted.com%evil.com/', 'https://trusted.com%evil.com/'],
    ['ws://trusted.com%evil.com/chat', 'ws://trusted.com%evil.com/chat'],
    ['wss://trusted.com%evil.com/chat', 'wss://trusted.com%evil.com/chat']
  ]

  t.plan(cases.length)

  cases.forEach(([input, expected]) => {
    t.equal(fastURI.normalize(input), expected, input)
  })
})

test('parse preserves encoded authority delimiters in host', (t) => {
  const cases = [
    ['http://trusted.com%evil.com/', 'trusted.com%evil.com'],
    ['http://example.com%A/', 'example.com%A'],
    ['http://user%Apass%evil.com/', 'user%Apass%evil.com']
  ]

  t.plan(cases.length)

  cases.forEach(([input, expectedHost]) => {
    t.equal(fastURI.parse(input).host, expectedHost, input)
  })
})

test('equal returns false when encoded delimiters differ from live delimiters', (t) => {
  const pairs = [
    ['http://trusted.com%evil.com/', 'http://trusted.com@evil.com/'],
    ['http://example.com%A/', 'http://example.com:/']
  ]

  t.plan(pairs.length)

  pairs.forEach(([left, right]) => {
    t.equal(fastURI.equal(left, right, {}), false, `${left} != ${right}`)
  })
})

test('resolve preserves encoded authority delimiters', (t) => {
  const result = fastURI.resolve('http://base.com/', '//trusted.com%evil.com/path')
  const parsed = fastURI.parse(result)

  t.plan()
  t.notEqual(parsed.host, 'evil.com', '//trusted.com%evil.com/path')
})

test('serialize escapes authority delimiters in host field', (t) => {
  const result = fastURI.serialize({ scheme: 'http', host: 'trusted.com@evil.com', path: '/' })
  const parsed = fastURI.parse(result)

  t.plan()
  t.notEqual(parsed.host, 'evil.com', 'host: trusted.com@evil.com')
})

test('normalize does not double-decode % into a live @', (t) => {
  const result = fastURI.normalize('http://trusted.com%evil.com/')
  const parsed = fastURI.parse(result)

  t.plan()
  t.notEqual(parsed.host, 'trusted.com@evil.com', 'http://trusted.com%evil.com/')
})
