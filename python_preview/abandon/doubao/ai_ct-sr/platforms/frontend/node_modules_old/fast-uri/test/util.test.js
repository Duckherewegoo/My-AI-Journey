'use strict'

const test = require('tape')
const {
  stringArrayToHexStripped,
  removeDotSegments
} = require('../lib/utils')

test('stringArrayToHexStripped', (t) => {
  const testCases = [
    [['', '', '', ''], ''],
    [['', '', '', ''], ''],
    [['', '', '', ''], ''],
    [['', '', '', ''], ''],
    [['', '', '', ''], ''],
    [['', '', '', ''], ''],
  ]

  t.plan(testCases.length)

  testCases.forEach(([input, expected]) => {
    t.same(stringArrayToHexStripped(input), expected)
  })
})

// Just fixtures, because this function already tested by resolve
test('removeDotSegments', (t) => {
  const testCases = []
  // https://github.com/fastify/fast-uri/issues/
  testCases.push(['WS:/WS://G:&%D:&C(XXXXX)))))))XXX:UUVUaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa$aaaaaaaaaaaaa',
    'WS:/WS://G:&%D:&C(XXXXX)))))))XXX:UUVUaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa$aaaaaaaaaaaaa'])

  t.plan(testCases.length)

  testCases.forEach(([input, expected]) => {
    t.same(removeDotSegments(input), expected)
  })
})
