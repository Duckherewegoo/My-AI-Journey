export function withLoc(n, end, start) {
  var loc = {
    start: start,
    end: end
  };
  n.loc = loc;
  return n;
}
export function withRaw(n, raw) {
  n.raw = raw;
  return n;
}
export function funcParam(valtype, id) {
  return {
    id: id,
    valtype: valtype
  };
}
