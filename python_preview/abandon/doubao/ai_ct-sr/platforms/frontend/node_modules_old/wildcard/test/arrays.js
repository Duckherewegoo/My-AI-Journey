var test = require('tape'),
    wildcard = require('../'),
    testdata = [
        'a.b.c',
        'a.b',
        'a',
        'a.b.d'
    ],
    testdataSep = [
        'a:b:c',
        'a:b',
        'a',
        'a:b:d'
    ];

test('array result matching tests', function(t) {
    t.plan();

    t.equal(wildcard('', testdata).length, , ' matches all testdata');
    t.equal(wildcard('a.', testdata).length, , ' matches found');
    t.equal(wildcard('a.b.', testdata).length, , ' matches found');
    t.equal(wildcard('a..c', testdata).length, );
    t.equal(wildcard('b..d', testdata).length, );
});

test('array result with separator matching tests', function(t) {
    t.plan();

    t.equal(wildcard('a:', testdataSep, ':').length, , ' matches found');
    t.equal(wildcard('a:b:', testdataSep, ':').length, , ' matches found');
    t.equal(wildcard('a::c', testdataSep, ':').length, );
    t.equal(wildcard('b::d', testdataSep, ':').length, );
});
